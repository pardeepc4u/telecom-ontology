"""Runs the fixed question set (questions.py) against all three retrieval
modes — vector-only, graph-only, hybrid — regardless of what the router
would pick for each question, since the point is to compare the modes
directly, not to test the router. Scores each against independently
computed ground truth (ground_truth.py) and writes results to
eval/results.json plus a markdown table appended into docs/EVALUATION.md.

Usage:
    python -m eval.run_eval
"""

import json
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from retrieval import graph_retrieval, vector_retrieval
from retrieval.fusion import fuse
from .ground_truth import ground_truth_for
from .metrics import precision_recall_f1
from .questions import QUESTIONS

TOP_K = 30
RESULTS_PATH = Path(__file__).resolve().parent / "results.json"
EVALUATION_DOC_PATH = Path(__file__).resolve().parents[1] / "docs" / "EVALUATION.md"


def run_graph_only(question: str) -> list[str]:
    result = graph_retrieval.structural_ticket_recall(question, limit=TOP_K)
    return [hit["ticket_id"] for hit in result["hits"]]


def run_vector_only(question: str) -> list[str]:
    hits = vector_retrieval.search(question, top_k=TOP_K)
    return [hit["ticket_id"] for hit in hits]


def run_hybrid(question: str) -> list[str]:
    with ThreadPoolExecutor(max_workers=2) as executor:
        structural_future = executor.submit(graph_retrieval.structural_ticket_recall, question, TOP_K)
        semantic_future = executor.submit(vector_retrieval.search, question, TOP_K)
        structural = structural_future.result()
        semantic = semantic_future.result()
    fused = fuse(structural["hits"], semantic, top_k=TOP_K)
    return [hit["ticket_id"] for hit in fused]


MODES = {
    "graph_only": run_graph_only,
    "vector_only": run_vector_only,
    "hybrid": run_hybrid,
}


def evaluate() -> list[dict]:
    rows = []
    for question in QUESTIONS:
        relevant_ids = ground_truth_for(question)
        for mode_name, run_fn in MODES.items():
            retrieved_ids = run_fn(question["question"])
            metrics = precision_recall_f1(retrieved_ids, relevant_ids)
            rows.append({
                "id": question["id"],
                "category": question["category"],
                "question": question["question"],
                "mode": mode_name,
                "retrieved_count": len(retrieved_ids),
                "ground_truth_count": len(relevant_ids),
                **{k: round(v, 3) for k, v in metrics.items()},
            })
            print(f"{question['id']:>3} [{mode_name:>11}] "
                  f"P={metrics['precision']:.2f} R={metrics['recall']:.2f} F1={metrics['f1']:.2f}")
    return rows


def category_averages(rows: list[dict]) -> dict:
    averages = {}
    for row in rows:
        key = (row["category"], row["mode"])
        averages.setdefault(key, []).append(row["f1"])
    return {key: round(sum(scores) / len(scores), 3) for key, scores in averages.items()}


def render_markdown_table(rows: list[dict], averages: dict) -> str:
    categories = ["structural_favorable", "semantic_favorable", "hybrid_favorable"]
    modes = ["graph_only", "vector_only", "hybrid"]

    lines = [
        "### Mean F1 by category and mode",
        "",
        "| Category | graph_only | vector_only | hybrid |",
        "|---|---|---|---|",
    ]
    for category in categories:
        cells = " | ".join(f"{averages[(category, mode)]:.3f}" for mode in modes)
        lines.append(f"| {category} | {cells} |")

    lines += ["", "### Per-question detail", "", "| Q | Category | Mode | Precision | Recall | F1 |", "|---|---|---|---|---|---|"]
    for row in rows:
        lines.append(
            f"| {row['id']} | {row['category']} | {row['mode']} | "
            f"{row['precision']:.2f} | {row['recall']:.2f} | {row['f1']:.2f} |"
        )

    return "\n".join(lines)


def update_evaluation_doc(markdown_table: str):
    """Replaces only the auto-generated table content between '## Results'
    and the next '## ' heading (e.g. a hand-written '## Findings' section),
    so re-running this script doesn't clobber written-up interpretation of
    the numbers."""
    content = EVALUATION_DOC_PATH.read_text()
    marker = "## Results"
    if marker not in content:
        raise ValueError(f"{EVALUATION_DOC_PATH} has no '## Results' section to update")

    head, _, rest = content.partition(marker)
    next_heading_pos = rest.find("\n## ", 1)
    tail = rest[next_heading_pos:] if next_heading_pos != -1 else ""

    new_content = (
        f"{head}{marker}\n\n"
        f"Generated by `python -m eval.run_eval` against the live stack. "
        f"Raw per-question results in `eval/results.json`.\n\n"
        f"{markdown_table}\n"
        f"{tail}"
    )
    EVALUATION_DOC_PATH.write_text(new_content)


def main():
    rows = evaluate()
    averages = category_averages(rows)

    RESULTS_PATH.write_text(json.dumps({
        "top_k": TOP_K,
        "rows": rows,
        "category_mode_mean_f1": {f"{cat}/{mode}": val for (cat, mode), val in averages.items()},
    }, indent=2))
    print(f"\nWrote {RESULTS_PATH}")

    markdown_table = render_markdown_table(rows, averages)
    update_evaluation_doc(markdown_table)
    print(f"Updated {EVALUATION_DOC_PATH}")


if __name__ == "__main__":
    main()
